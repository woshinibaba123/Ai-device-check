"""Reusable business skeletons; parameters and expected outcomes come from Excel."""
import re

RULES={
'clean':'''清洁机器人流程骨架：按用例角色登录→选择用例门店→核对机器人名称/编号→进入清洁机器人详情→按本条用例分支操作→回读并验证→返回。
改名：读取原名→填写用例名称→按用例保存或取消→重新进入核对；不要把保存与取消混用。
排班：进入排班→新增/编辑→绑定用例指定区域、日期、时间、重复周期与模式→按用例保存/取消→核对列表及详情。区域缺失只阻塞依赖区域的步骤，继续独立项。禁止套用其他用例的排班ID。
模式：读取当前模式→按用例新增或编辑参数→保存/取消→重新读取验证；缺少控件或接口证据则受阻，不编造。
记录和报告：按用例筛选日期/状态→核对列表或空态→进入实际存在的详情→核对字段→返回。默认只读，不能把进入详情当成核对通过。''',
'call':'''呼叫任务流程骨架：按用例角色登录→选择指定门店→选择指定机器人并核对身份和在线/可用状态→选择用例点位及任务类型→核对选择→按用例下发或取消→观察实际结果→返回。
下发用源码确认的dispatch专用动作及具体呼叫接口，不得用普通save绕过校验；需要关联本次返回任务ID，历史任务不能冒充本次结果。
取消仅针对本次创建且唯一识别的任务；复用流程不得复用旧任务ID。现有执行器不支持的取消/状态验证必须明确标记受阻，不能生成不存在的action。
成功提示或接口成功仅证明相应阶段成功；Excel要求机器人移动、到达、任务完成时，必须保留对应运行时验证，不能降级为只验接口。结果不明先核对，禁止重复下发。离线、无点位、无权限等按原用例预期处理。'''
}

def context(cases):
    text='\n'.join(str(c.get(k,'')) for c in cases for k in ('module','title','steps'))
    domains=[]
    if re.search(r'清洁|清扫|排班|清洁模式',text):domains.append('clean')
    if re.search(r'呼叫|多点任务|配送任务|下发任务',text):domains.append('call')
    return '\n'.join(RULES[d] for d in domains)
